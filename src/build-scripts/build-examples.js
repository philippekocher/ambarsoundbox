import fs from 'fs'
import path from 'path'

const headerComment = `
/* -------------------------------------------------
   THIS FILE IS AUTO-GENERATED. DO NOT EDIT MANUALLY
   Generated by: build-examples.js
-------------------------------------------------- */`

const presetsDir = './src/examples'
const outputFilePath = './src/examples/examples.gen.js'

const files = fs.readdirSync(presetsDir)
  .filter(file => file.endsWith('.json'))

  
const imports = files.map(file => {
  const fullPath = path.join(presetsDir, file)
  const fileName = file.substring(0, file.lastIndexOf('.'))
  const content = fs.readFileSync(fullPath, 'utf-8')
  return `\t{name: "${fileName}", content: '${content}'}`}
  ).join(',\n');
  
fs.writeFileSync(outputFilePath, `${headerComment}\n\nexport const examples = [\n${imports}\n]`); 
