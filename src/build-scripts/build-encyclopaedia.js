import fs from 'fs'
import path from 'path'
import matter from "gray-matter";
import { marked } from "marked";

const headerComment = `
/* -------------------------------------------------
   THIS FILE IS AUTO-GENERATED. DO NOT EDIT MANUALLY
   Generated by: build-encyclopaedia.js
-------------------------------------------------- */`

const srcDir = './src/encyclopaedia'
const outDir = './src/encyclopaedia'

// Encyclopaedia content (src/encyclopaedia/<lang>/) is git-ignored: it's
// content, not code, and each clone supplies its own — a fresh clone may
// have no language subdirectories at all. Whichever subdirectories DO exist
// here become the encyclopaedia's list of available languages, written out
// below to languages.gen.js. encyclopaedia.js reads that list to build its
// loaders, so it never tries to import a gen.js file that wasn't generated.
const languages = fs.readdirSync(srcDir, { withFileTypes: true })
  .filter(d => d.isDirectory() && !d.name.startsWith("."))
  .map(d => d.name)

fs.writeFileSync(
  path.join(outDir, 'languages.gen.js'),
  `${headerComment}\n\nexport const languages = ${JSON.stringify(languages)}\n`,
  "utf-8"
)

for (const lang of languages) {
  const dir = path.join(srcDir, lang)
  const files = fs.readdirSync(dir).filter(f => f.endsWith(".md") && !f.startsWith("."))

  const entries = files.map(file => {
    const raw = fs.readFileSync(path.join(dir, file), "utf-8")
    const { data, content } = matter(raw)

    if (!data.id) {
      console.error(
        `\x1b[1m\x1b[31mError:\x1b[0m no id "${data.id}" in ${lang}/${file}`
      )
      process.exit(1)
    }

    return {
      id: data.id,
      title: data.title,
      modules: data.modules ?? [],
      html: marked.parse(content),
      _file: file // only for duplicate reporting
    }
  })

  entries.sort((a, b) => a.title.localeCompare(b.title, lang))

  const seen = new Map()
  for(const entry of entries) {
    if(seen.has(entry.id)) {
      console.error(
        `\x1b[1m\x1b[31mError:\x1b[0m Duplicate id "${entry.id}" in ${lang}/${seen.get(entry.id)} and ${lang}/${entry._file}`
      )
      process.exit(1)
    }
    seen.set(entry.id, entry._file)
  }
  
  for (const entry of entries) {
    let html = entry.html
  
    for (const otherEntry of entries) {
      if (otherEntry.id === entry.id) continue
  
      const title = escapeRegExp(otherEntry.title)
      const re = new RegExp(
        `(?<![\\p{L}\\p{N}_])${title}(?![\\p{L}\\p{N}_])`,
        'giu'
      )
  
      html = html.replace(
        re,
        `<a href="/${otherEntry.id}">${otherEntry.title}</a>`
      )
    }
  
    entry.html = html
  }

  const groups = {}
  entries.forEach(entry => {
    const letter = entry.title[0].toLowerCase();
    (groups[letter] ??= []).push({ id: entry.id, title: entry.title})
  })

  const entriesObj = Object.fromEntries(
    entries.map(entry => [
      entry.id,
      {
        title: entry.title,
        modules: entry.modules,
        html: entry.html
      }
    ])
  )

  fs.writeFileSync(
    path.join(outDir, `encyclopaedia.${lang}.gen.js`),
    `${headerComment}\n\nexport const toc = ${JSON.stringify(groups, null, 2)}\n\nexport const entries = ${JSON.stringify(entriesObj, null, 2)}\n`,
    "utf-8"
  )
}

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}