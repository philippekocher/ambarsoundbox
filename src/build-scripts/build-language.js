import fs from 'fs'
import path from 'path'

const headerComment = `
/* -------------------------------------------------
   THIS FILE IS AUTO-GENERATED. DO NOT EDIT MANUALLY
   Generated by: build-language.js
-------------------------------------------------- */`

const csvPath = './src/i18n/dictionary.csv'
const outDir = './src/i18n/'


// Read and parse CSV
// ------------------

function parseCSV(text) {
  const rows = []
  let row = [], field = "", inQuotes = false;
  // Normalise line endings
  const src = text.replace(/\r\n/g, "\n").replace(/\r/g, "\n")
 
  for (let i = 0; i < src.length; i++) {
    const ch = src[i]
    const next = src[i + 1]
 
    if(inQuotes) {
      if(ch === '"' && next === '"') { // escaped quote
        field += '"'
        i++
      }       
      else if(ch === '"') {  // closing quote
        inQuotes = false
      }       
      else {
        field += ch
      }
    }
    else {
      if(ch === '"') {
        inQuotes = true
      }
      else if(ch === ',') {
        row.push(field)
        field = ""
      }
      else if(ch === "\n") {
        row.push(field)
        rows.push(row)
        row = []
        field = ""
      }
      else {
        field += ch
      }
    }
  }
  // Last field / row
  if(field || row.length) {
    row.push(field)
    rows.push(row)
  }
 
  return rows;
}

const raw   = fs.readFileSync(csvPath, "utf8")
const rows  = parseCSV(raw).filter(r => r.some(c => c.trim() !== ""))

if (rows.length < 2) {
  console.error("CSV must have at least a header row and one data row.");
  process.exit(1);
}
 
const [header, ...dataRows] = rows
let [, ...columnNames] = header
 
if(columnNames.length === 0) {
  console.error("No value columns found in the header.")
  process.exit(1)
}

columnNames = columnNames.filter(name => name != '')

fs.mkdirSync(outDir, { recursive: true })

fs.writeFileSync(
  path.join(outDir, 'languages.gen.js'),
  `${headerComment}\n\nexport const languages = ${JSON.stringify(columnNames)}\n`,
  "utf8"
)


// Build one object per column
// ---------------------------

const objects = columnNames.map(() => ({}))

for(const row of dataRows) {
  const [key, ...values] = row
  if(!key.trim()) continue
 
  values.forEach((val, colIdx) => {
    if(colIdx < objects.length) {
      objects[colIdx][key.trim()] = val.trim()
    }
  })
}
 
// Write output files
// --------------------

columnNames.forEach((colName, colIdx) => {
 
  const entries = Object.entries(objects[colIdx])
    .filter(([k, v]) => v != '')
    .map(([k, v]) => {
      let jsVal;
      if (v === "true")       jsVal = "true";
      else if (v === "false") jsVal = "false";
      else if (!isNaN(v))     jsVal = v;
      else                    jsVal = JSON.stringify(v);
  
      return `  ${k}: ${jsVal}`;
    })
    .join(",\n");
 
  if(entries.length > 0) {
    const filePath = path.join(outDir, `${colName}.gen.js`)
    const content = 
`${headerComment}

export default {
${entries}
} 
`
    fs.writeFileSync(filePath, content, "utf8")
  }
})